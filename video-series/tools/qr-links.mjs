#!/usr/bin/env node
/**
 * Compute the HashBin CID and QR URL for every snippet in qr-manifest.json.
 *
 *   node video-series/tools/qr-links.mjs                 write qr-links.json and qr-links.md
 *   node video-series/tools/qr-links.mjs --payloads DIR  also write the exact bytes to upload
 *   node video-series/tools/qr-links.mjs --upload [DIR]  only those files, for hashbin.org/upload
 *   node video-series/tools/qr-links.mjs --check         ask 256t.us whether each payload is stored
 *
 * A CID is a 6-byte length prefix plus either the content itself (64 bytes or fewer)
 * or its SHA-512 digest, so it is known before anything is uploaded. Payloads are
 * built with the editor's own HashBinDocuments.serialize, so saving a snippet with
 * the editor's "Save to HashBin" button (using the editor link listed for it, with the
 * same scene selection) stores exactly these bytes and therefore this CID. Dropping the
 * --upload folder's files on https://hashbin.org/upload stores the same bytes in one go.
 */
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const SERIES = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { HashBinDocuments } = require(join(SERIES, '..', 'src', 'hashbin.js'));
const { ShareLinks } = loadShareLinks();

function loadShareLinks() {
  // share-links.js defines globals for the page; evaluate it in a function scope instead.
  const source = readFileSync(join(SERIES, '..', 'src', 'share-links.js'), 'utf8');
  return new Function(`${source}\nreturn { ShareLinks };`)();
}

function cidFor(payload) {
  const bytes = Buffer.from(payload, 'utf8');
  const prefix = Buffer.alloc(6);
  prefix.writeUIntBE(bytes.length, 0, 6);
  const body = bytes.length <= 64 ? bytes : createHash('sha512').update(bytes).digest();
  const cid = prefix.toString('base64url') + body.toString('base64url');
  if (!HashBinDocuments.isCID(cid)) throw new Error('Computed an invalid CID.');
  return cid;
}

function payloadFor(entry, src) {
  if (entry.payload === 'plain') return src;
  return HashBinDocuments.serialize({ src, type: entry.type, scene: entry.scene || '', pos: entry.pos || {} });
}

function editorLink(site, entry, src) {
  // The uncompressed form of the editor's Share link: source in the fragment.
  return ShareLinks.build({ url: site, code: src, type: entry.type, scene: entry.scene || '', positions: entry.pos || {} }).long;
}

const args = process.argv.slice(2);
const manifest = JSON.parse(readFileSync(join(SERIES, 'qr-manifest.json'), 'utf8'));
const site = manifest.site;
const rows = manifest.snippets.map(entry => {
  const src = readFileSync(join(SERIES, entry.file), 'utf8');
  const payload = payloadFor(entry, src);
  const cid = cidFor(payload);
  const bytes = Buffer.byteLength(payload, 'utf8');
  return { ...entry, cid, bytes, inline: bytes <= 64, url: `${site}#${cid}`, editor: editorLink(site, entry, src), payload };
});

writeFileSync(join(SERIES, 'qr-links.json'), JSON.stringify(rows.map(({ payload, editor, ...row }) => row), null, 2) + '\n');

const table = [
  '# QR links',
  '',
  'Generated by `node video-series/tools/qr-links.mjs` from `qr-manifest.json`. Do not edit by hand.',
  'Every URL below is final: it is derived from the snippet bytes. Upload each non-inline payload',
  'to HashBin before publishing (see README.md, "QR codes"), then run the tool with `--check`.',
  '',
  '| QR | Ep | Title | Bytes | Needs upload | URL |',
  '|---|---|---|---|---|---|',
  ...rows.map(r => `| ${r.id} | ${r.episode} | ${r.title} | ${r.bytes} | ${r.inline ? 'no (inline)' : 'yes'} | ${r.url} |`),
  ''
].join('\n');
writeFileSync(join(SERIES, 'qr-links.md'), table);

const payloadIndex = args.indexOf('--payloads');
if (payloadIndex >= 0) {
  const dir = resolve(args[payloadIndex + 1] || join(SERIES, 'build', 'payloads'));
  mkdirSync(dir, { recursive: true });
  const links = [];
  for (const row of rows) {
    if (row.inline) continue;
    writeFileSync(join(dir, `${row.id}.${row.payload.startsWith('{') ? 'json' : 'txt'}`), row.payload);
    links.push(`${row.id}\t${row.cid}\t${row.editor}`);
  }
  writeFileSync(join(dir, 'editor-links.tsv'), 'id\texpected CID\teditor link (open, check the scene field, Save to HashBin)\n' + links.join('\n') + '\n');
  console.log(`Wrote ${links.length} payloads and editor-links.tsv to ${dir}`);
}

const uploadIndex = args.indexOf('--upload');
if (uploadIndex >= 0) {
  // Only the files to drop on https://hashbin.org/upload: its CID is computed from each
  // file's raw bytes, so every file must be exactly its payload and nothing else may be here.
  const dir = resolve(args[uploadIndex + 1] || join(SERIES, 'build', 'hashbin-upload'));
  mkdirSync(dir, { recursive: true });
  for (const name of readdirSync(dir)) {
    if (/^q\d\d-\d\d\.(json|txt)$/.test(name)) unlinkSync(join(dir, name));
  }
  const stray = readdirSync(dir).filter(name => !name.startsWith('.'));
  if (stray.length) throw new Error(`${dir} holds other files (${stray.join(', ')}); they would be uploaded too.`);
  const pending = rows.filter(row => !row.inline);
  for (const row of pending) {
    const file = join(dir, `${row.id}.${row.payload.startsWith('{') ? 'json' : 'txt'}`);
    writeFileSync(file, row.payload);
    if (cidFor(readFileSync(file, 'utf8')) !== row.cid) throw new Error(`${file} does not hash to ${row.cid}.`);
  }
  const total = pending.reduce((sum, row) => sum + row.bytes, 0);
  console.log(`Wrote ${pending.length} files (${total} bytes) to ${dir}; each hashes to its QR link's CID.`);
}

if (args.includes('--check')) {
  let missing = 0;
  for (const row of rows) {
    if (row.inline) { console.log(`ok       ${row.id} inline`); continue; }
    try {
      const response = await fetch(`https://256t.us/${row.cid}`);
      const text = response.ok ? await response.text() : null;
      const status = text === row.payload ? 'ok' : response.ok ? 'MISMATCH' : `MISSING (HTTP ${response.status})`;
      if (status !== 'ok') missing++;
      console.log(`${status.padEnd(8)} ${row.id} ${row.title}`);
    } catch (error) {
      missing++;
      console.log(`ERROR    ${row.id} ${error.message}`);
    }
  }
  console.log(`\n${missing} QR link(s) not yet resolvable`);
  process.exitCode = missing ? 1 : 0;
} else {
  console.log(`Wrote qr-links.json and qr-links.md for ${rows.length} snippets (${rows.filter(r => !r.inline).length} need uploading).`);
}
