// Writes offline-hashes.js: SHA-256 for every file the service worker may store or serve.
// Cache Storage is shared with sibling apps on this origin, so only matching bytes are served.
// Usage: node scripts/update-offline-hashes.mjs [--check] [--fetch]
// --fetch hashes pinned remote files missing from scripts/remote-hashes.json.
import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const root = new URL('../', import.meta.url);
const Assets = require('../offline-assets.js');
const sha = data => createHash('sha256').update(data).digest('hex');
const pinnedFile = new URL('scripts/remote-hashes.json', root);
const pinned = JSON.parse(fs.readFileSync(pinnedFile, 'utf8'));
const hashes = {};
for (const path of Assets.local) hashes[path] = sha(fs.readFileSync(new URL(path, root)));
for (const url of [...Assets.remote, ...Assets.runtime, ...Assets.optional]) {
  if (!pinned[url]) {
    if (!process.argv.includes('--fetch')) throw new Error('No pinned hash for ' + url + '. Run with --fetch.');
    const response = await fetch(url);
    if (!response.ok) throw new Error('Could not fetch ' + url);
    pinned[url] = sha(Buffer.from(await response.arrayBuffer()));
  }
  hashes[url] = pinned[url];
}
const output = '/** Generated by node scripts/update-offline-hashes.mjs after changing any offline file. */\nconst OfflineHashes = ' +
  JSON.stringify(hashes, null, 2) + ";\nif (typeof module !== 'undefined') module.exports = OfflineHashes;\nelse globalThis.OfflineHashes = OfflineHashes;\n";
const target = new URL('offline-hashes.js', root);
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw new Error('offline-hashes.js is stale. Run node scripts/update-offline-hashes.mjs.');
} else {
  fs.writeFileSync(target, output);
  if (process.argv.includes('--fetch')) fs.writeFileSync(pinnedFile, JSON.stringify(pinned, null, 2) + '\n');
}
console.log(Object.keys(hashes).length + ' offline hashes ' + (process.argv.includes('--check') ? 'verified.' : 'written.'));
